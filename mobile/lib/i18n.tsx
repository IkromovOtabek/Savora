const dicts: Record<Locale, Dict> = { uz, ru };

/** Hook'siz joylar (api.ts, format.ts) uchun joriy til — provayder yangilab turadi. */
let current: Locale = DEFAULT_LOCALE;
export function getLocale(): Locale { return current; }
export function getDict(locale: Locale = current): Dict { return dicts[locale]; }

interface I18nState {
  locale: Locale;
  d: Dict;
  setLocale: (l: Locale) => void;
}

const I18nContext = createContext<I18nState | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(DEFAULT_LOCALE);

  useEffect(() => {
    AsyncStorage.getItem(LANG_KEY)
      .then((v) => { if (isLocale(v)) { current = v; setLocaleState(v); } })
      .catch(() => { /* saqlangan tanlov o'qilmasa — standart til */ });
  }, []);

  const setLocale = useCallback((l: Locale) => {
    current = l;
    setLocaleState(l);
    AsyncStorage.setItem(LANG_KEY, l).catch(() => { /* keyingi ochilishda standart til */ });
  }, []);

  // Render'dan oldin modul qiymatini sinxron ushlab turamiz (format/api uchun)
  current = locale;
  const value = useMemo<I18nState>(() => ({ locale, d: dicts[locale], setLocale }), [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n I18nProvider ichida bo\'lishi kerak');
  return ctx;
}

export function useDict(): Dict {
  return useI18n().d;
}
